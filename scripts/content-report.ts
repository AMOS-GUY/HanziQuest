/**
 * Curriculum quality report (Markdown).
 *   npm run content:report -- [file] [--out report.md]
 * Static checks on the content file, plus the live-database report (features/curriculum/quality.ts)
 * for DATABASE_URL. Read-only.
 */
import "dotenv/config";
import fs from "node:fs";
import path from "node:path";
import { loadStrokeData } from "../src/features/curriculum/stroke-data";
import {
  CONTENT_LIMITS,
  validateCurriculumContent,
} from "../src/features/curriculum/validate-content";
import { contentQualityReport } from "../src/features/curriculum/quality";
import { createPrismaClient } from "../src/lib/database/client";

async function main() {
  const args = process.argv.slice(2);
  const outIndex = args.indexOf("--out");
  const out = outIndex >= 0 ? args[outIndex + 1] : undefined;
  const file =
    args.find((a, i) => !a.startsWith("--") && i !== outIndex + 1) ?? "content/hsk1-starter.json";
  const raw = JSON.parse(fs.readFileSync(path.resolve(file), "utf8"));
  const result = validateCurriculumContent(raw, loadStrokeData);
  const lines: string[] = [];
  const push = (...l: string[]) => lines.push(...l);

  push(`# Curriculum quality report`, "");
  push(
    `Generated by \`npm run content:report\` on ${new Date().toISOString().slice(0, 10)}. Read-only.`,
    "",
  );
  push(`## Content file: \`${file}\``, "");
  if (result.content) {
    const c = result.content;
    const lessons = c.units.flatMap((u) => u.lessons);
    const newPerLesson: number[] = [];
    const seen = new Set<string>();
    for (const lesson of lessons) {
      const fresh = new Set(
        lesson.words.flatMap((w) => [...w.simplified]).filter((h) => !seen.has(h)),
      );
      fresh.forEach((h) => seen.add(h));
      newPerLesson.push(fresh.size);
    }
    const withStrokes = Object.keys(c.characters).filter((h) => loadStrokeData(h) !== null).length;
    push(
      "| | |",
      "| --- | --- |",
      `| Curriculum | ${c.curriculum.name} (${c.curriculum.framework} ${c.curriculum.version}) |`,
      `| Verification | **${c.curriculum.verification}** |`,
      `| Licence | ${c.curriculum.licenseStatus} |`,
      `| Units / lessons | ${c.units.length} / ${lessons.length} |`,
      `| Words | ${result.stats.words} |`,
      `| Characters | ${result.stats.characters} (${withStrokes} with stroke data) |`,
      `| New characters per lesson | min ${Math.min(...newPerLesson)}, max ${Math.max(...newPerLesson)}, suggested at most ${CONTENT_LIMITS.newCharactersPerLesson} |`,
      `| Words with an example sentence | 0 (the file format has no example field yet) |`,
      "",
    );
  }
  const errors = result.issues.filter((i) => i.severity === "error");
  const warnings = result.issues.filter((i) => i.severity === "warning");
  push(
    `Validation: **${result.ok ? "passed" : "failed"}**: ${errors.length} errors, ${warnings.length} warnings.`,
    "",
  );
  for (const i of result.issues) push(`- ${i.severity.toUpperCase()} \`${i.path}\`: ${i.message}`);
  if (result.issues.length > 0) push("");

  if (process.env.DATABASE_URL) {
    const prisma = createPrismaClient();
    try {
      const report = await contentQualityReport(prisma);
      const dbName = new URL(process.env.DATABASE_URL).pathname.slice(1);
      push(`## Database: \`${dbName}\``, "");
      push("| Curriculum | Status | Verification | Licence | Lessons (published / draft) |");
      push("| --- | --- | --- | --- | --- |");
      for (const c of report.curricula)
        push(
          `| ${c.name} | ${c.status} | ${c.verification} | ${c.licenseStatus} | ${c.publishedLessons} / ${c.draftLessons} |`,
        );
      const t = report.totals;
      push(
        "",
        `Characters: ${t.characters} (${JSON.stringify(t.charactersByVerification)}). Words: ${t.words} (${JSON.stringify(t.wordsByVerification)}); ${t.wordsWithoutExample} without an example, ${t.wordsWithoutAudio} without audio. Published exercises: ${t.publishedExercises}.`,
        "",
      );
      if (report.findings.length === 0) push("No findings.");
      for (const f of report.findings)
        push(`- ${f.severity.toUpperCase()} (${f.area}) ${f.key}: ${f.message}`);
      push("");
    } finally {
      await prisma.$disconnect();
    }
  }

  const text = `${lines.join("\n")}\n`;
  if (out) fs.writeFileSync(path.resolve(out), text);
  else process.stdout.write(text);
  if (!result.ok) process.exit(1);
}

main().catch((error) => {
  console.error(error);
  process.exit(1);
});
